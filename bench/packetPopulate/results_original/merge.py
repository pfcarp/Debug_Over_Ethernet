import csv
from pathlib import Path

RESULTS_DIR = Path("./")
OUTPUT_FILE = "combined.csv"
FILENAME_COLUMN = "packet"

rows = []
header = None

for csv_file in sorted(RESULTS_DIR.glob("*.csv")):
    with csv_file.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)

        if reader.fieldnames is None:
            raise ValueError(f"{csv_file.name} has no header")

        if header is None:
            header = list(reader.fieldnames)
        else:
            if list(reader.fieldnames) != header:
                raise ValueError(
                    f"Header mismatch in {csv_file.name}: "
                    f"{reader.fieldnames} != {header}"
                )

        try:
            row = next(reader)
        except StopIteration:
            raise ValueError(f"{csv_file.name} has no data row")

        row[FILENAME_COLUMN] = csv_file.stem
        rows.append(row)

if header is None:
    raise RuntimeError("No CSV files found in results directory")

with open(OUTPUT_FILE, "w", newline="", encoding="utf-8") as f:
    writer = csv.DictWriter(
        f,
        fieldnames=[FILENAME_COLUMN]+header,
    )
    writer.writeheader()
    writer.writerows(rows)

print(f"Wrote {len(rows)} rows to {OUTPUT_FILE}")
